#!/usr/bin/env bash
# =============================================================================
# RedGate One-Step Server / VM Secret Bootstrapper
# Generates cryptographically random operator tokens, writes ONLY their SHA-256
# hashes into .env, creates secrets/llm_api_key (0600), and prints the plaintext
# operator tokens ONCE to stdout so you can copy them safely.
# =============================================================================
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="${ROOT_DIR}/.env"
SECRET_DIR="${ROOT_DIR}/secrets"
LLM_KEY_FILE="${SECRET_DIR}/llm_api_key"

if [[ -f "$ENV_FILE" && "${1:-}" != "--force" ]]; then
  printf '[RedGate] %s already exists. Re-run with --force to regenerate all tokens.\n' "$ENV_FILE" >&2
  exit 1
fi

gen_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1"
  else
    python3 -c "import secrets; print(secrets.token_hex($1))"
  fi
}

sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    printf '%s' "$1" | sha256sum | awk '{print $1}'
  else
    python3 -c "import hashlib, sys; print(hashlib.sha256(sys.argv[1].encode()).hexdigest())" "$1"
  fi
}

INTERNAL_TOKEN="$(gen_hex 32)"
TOK_ALICE="rg_op_$(gen_hex 20)"
TOK_SARA="rg_lead_$(gen_hex 20)"
TOK_KAVEH="rg_adm_$(gen_hex 20)"

HASH_ALICE="$(sha256_of "$TOK_ALICE")"
HASH_SARA="$(sha256_of "$TOK_SARA")"
HASH_KAVEH="$(sha256_of "$TOK_KAVEH")"

mkdir -p "$SECRET_DIR" "${ROOT_DIR}/data"
chmod 700 "$SECRET_DIR"

if [[ ! -f "$LLM_KEY_FILE" ]]; then
  printf '%s' "mock-mode-placeholder-rotate-before-live-llm" > "$LLM_KEY_FILE"
  chmod 600 "$LLM_KEY_FILE"
fi

umask 077
cat > "$ENV_FILE" <<EOF
# Generated by scripts/bootstrap_env.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
REDGATE_BIND_ADDR=127.0.0.1
REDGATE_DB_PATH=/app/data/redgate.db
REDGATE_CONFIG_DIR=/app/config
REDGATE_INTERNAL_TOKEN=${INTERNAL_TOKEN}
REDGATE_MCP_URL=http://mcp-server:8001
REDGATE_SANDBOX_URL=http://sandbox-runner:8002

REDGATE_TOKEN_HASH_OP_ALICE=${HASH_ALICE}
REDGATE_TOKEN_HASH_LEAD_SARA=${HASH_SARA}
REDGATE_TOKEN_HASH_ADMIN_KAVEH=${HASH_KAVEH}

# Switch REDGATE_LLM_MODE to openai_compatible to use Ollama / vLLM / OpenAI
REDGATE_LLM_MODE=mock
REDGATE_LLM_BASE_URL=http://host.docker.internal:11434/v1
REDGATE_LLM_MODEL=qwen2.5-coder:14b
REDGATE_STRICT_DNS_RESOLVE=false
REDGATE_DEMO_MODE=false
EOF

cat <<EOF
=====================================================================
 RedGate Secrets Initialized (.env + secrets/llm_api_key, mode 0600)
 SAVE THESE BEARER TOKENS NOW — only SHA-256 hashes are stored in .env
=====================================================================
  op-alice    (operator) : ${TOK_ALICE}
  lead-sara   (approver) : ${TOK_SARA}
  admin-kaveh (admin)    : ${TOK_KAVEH}
=====================================================================
Next step (Docker Compose):
  docker compose up -d --build
  open http://127.0.0.1:8000  (paste any Bearer token above)
EOF
